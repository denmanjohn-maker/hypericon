#!/usr/bin/env python3
"""Builds the website's theme assets from Themes/: one artwork sprite sheet per theme, the plain
folders in each tag colour (assets/base/), and themes.js."""
import json
import os

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
THEMES = os.path.join(ROOT, "Themes")
ASSETS = os.path.join(ROOT, "site", "assets")
CELL, COLS = 128, 9
GROUPS = ["Holidays", "Sci-Fi", "80s", "Computer Retro", "OS Classics"]

os.makedirs(os.path.join(ASSETS, "base"), exist_ok=True)
for name in sorted(os.listdir(os.path.join(THEMES, "_base"))):
    Image.open(os.path.join(THEMES, "_base", name)).convert("RGBA").resize((CELL, CELL), Image.LANCZOS).save(
        os.path.join(ASSETS, "base", name), optimize=True)

categories = json.load(open(os.path.join(THEMES, "categories.json")))
ids = [c["id"] for c in categories]
themes = []
for name in sorted(os.listdir(THEMES)):
    manifest_path = os.path.join(THEMES, name, "theme.json")
    if name.startswith("_") or not os.path.exists(manifest_path):
        continue
    manifest = json.load(open(manifest_path))
    rows = (len(ids) + COLS - 1) // COLS
    sheet = Image.new("RGBA", (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, cat in enumerate(ids):
        resample = Image.NEAREST if name == "8-bit-pixel" else Image.LANCZOS
        icon = Image.open(os.path.join(THEMES, name, f"{cat}.png")).convert("RGBA").resize((CELL, CELL), resample)
        sheet.paste(icon, ((i % COLS) * CELL, (i // COLS) * CELL))
    sheet.save(os.path.join(ASSETS, "sprites", f"{name}.png"), optimize=True)
    themes.append({k: manifest[k] for k in ("id", "name", "group", "description")})

themes.sort(key=lambda t: (GROUPS.index(t["group"]) if t["group"] in GROUPS else 99, t["name"]))
with open(os.path.join(ASSETS, "themes.js"), "w") as f:
    f.write("// Generated by tools/site/build.py\n")
    f.write(f"window.HYPERICON = {json.dumps({'cols': COLS, 'categories': categories, 'themes': themes}, indent=1)};\n")
print(f"{len(themes)} sprites written")
